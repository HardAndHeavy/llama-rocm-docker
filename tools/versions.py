#!/usr/bin/env python3
"""Single source of truth for the pinned software stack.

`versions.json` is the authoritative list of pinned versions. Everything else is
generated from it: the base image reference, the source revisions, the build and
runtime requirement inputs, the labels block and the README stack table. The
stack therefore cannot drift between the places it is written down.

Usage:
    python3 tools/versions.py check        # verify every generated block is current
    python3 tools/versions.py sync         # rewrite the generated files
    python3 tools/versions.py args         # print the Dockerfile ARG block
    python3 tools/versions.py labels       # print the Dockerfile LABEL block
    python3 tools/versions.py readme       # print the README version table
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSIONS_FILE = ROOT / "versions.json"

GENERATED_HEADER = (
    "GENERATED by tools/versions.py from versions.json - do not edit by hand."
)

ARGS_BEGIN = "# BEGIN GENERATED: tools/versions.py args\n"
ARGS_END = "# END GENERATED\n"
LABELS_BEGIN = "# BEGIN GENERATED: tools/versions.py labels\n"
LABELS_END = "# END GENERATED\n"
README_BEGIN = "<!-- versions:begin -->\n"
README_END = "<!-- versions:end -->\n"


def load() -> dict:
    with VERSIONS_FILE.open(encoding="utf-8") as handle:
        return json.load(handle)


def base_reference(data: dict) -> str:
    """Fully qualified, digest-pinned base image reference."""
    image = data["image"]
    reference = f'{image["base_image"]}:{image["base_version"]}'
    digest = image["base_digest"]
    if not digest.startswith("sha256:") or "REPLACE" in digest:
        raise SystemExit(
            "image.base_digest in versions.json is not a resolved digest.\n"
            "Publish the base image first, then run `make pin-base`."
        )
    return f"{reference}@{digest}"


def build_requirements_in(data: dict) -> str:
    """Toolchain used to compile llama.cpp, thrown away in the builder stage."""
    build = data["build"]
    return (
        f"# {GENERATED_HEADER}\n"
        "# CPython 3.14, Linux x86_64. Build-time only: scikit-build-core drives\n"
        "# CMake, cmake and ninja compile llama.cpp, setuptools/wheel back the\n"
        "# non-isolated build required by `--no-build-isolation`.\n"
        + "".join(
            f"{name}=={build[name]}\n"
            for name in (
                "scikit-build-core",
                "setuptools",
                "wheel",
                "cmake",
                "ninja",
            )
        )
    )


def runtime_requirements_in(data: dict) -> str:
    """What llama-cpp-python imports at runtime but the base image lacks."""
    return (
        f"# {GENERATED_HEADER}\n"
        "# Runtime dependencies of llama-cpp-python that the base image does not\n"
        "# already provide. numpy, jinja2 and typing-extensions come from the\n"
        "# base image and are constrained by it, so they are not listed here.\n"
        + "".join(f"{name}=={version}\n" for name, version in data["runtime"].items())
    )


def args_block(data: dict) -> str:
    """The build arguments that pin every external input of the image."""
    build = data["build"]
    sources = data["sources"]
    return (
        f"ARG IMAGE_VERSION={data['image']['version']}\n"
        f"ARG BASE_IMAGE={base_reference(data)}\n"
        f"ARG LLAMA_CPP_PYTHON_VERSION={sources['llama_cpp_python']['version']}\n"
        f"ARG LLAMA_CPP_PYTHON_REVISION={sources['llama_cpp_python']['revision']}\n"
        f"ARG LLAMA_CPP_VERSION={sources['llama_cpp']['version']}\n"
        f"ARG LLAMA_CPP_REVISION={sources['llama_cpp']['revision']}\n"
        f"ARG AMDGPU_TARGETS=\"{build['amd_gpu_targets']}\"\n"
    )


def labels_block(data: dict) -> str:
    image = data["image"]
    sources = data["sources"]
    build = data["build"]
    labels = {
        "org.opencontainers.image.title": "llama-rocm",
        "org.opencontainers.image.description": (
            "llama.cpp with ROCm support for AMD Radeon GPUs"
        ),
        "org.opencontainers.image.source": (
            "https://github.com/HardAndHeavy/llama-rocm-docker"
        ),
        "org.opencontainers.image.url": "https://hub.docker.com/r/hardandheavy/llama-rocm",
        "org.opencontainers.image.documentation": (
            "https://github.com/HardAndHeavy/llama-rocm-docker#readme"
        ),
        "org.opencontainers.image.licenses": "Apache-2.0",
        "org.opencontainers.image.version": "${IMAGE_VERSION}",
        "org.opencontainers.image.revision": "${IMAGE_REVISION}",
        "org.opencontainers.image.created": "${IMAGE_CREATED}",
        "org.opencontainers.image.base.name": (
            f"{image['base_image']}:{image['base_version']}"
        ),
        "org.opencontainers.image.base.digest": image["base_digest"],
        "ru.hardandheavy.llama-cpp-python.version": (
            sources["llama_cpp_python"]["version"]
        ),
        "ru.hardandheavy.llama-cpp-python.revision": (
            sources["llama_cpp_python"]["revision"]
        ),
        "ru.hardandheavy.llama-cpp.version": sources["llama_cpp"]["version"],
        "ru.hardandheavy.llama-cpp.revision": sources["llama_cpp"]["revision"],
        "ru.hardandheavy.amdgpu-targets": build["amd_gpu_targets"],
    }
    lines = [f'{key}="{value}" \\' for key, value in labels.items()]
    return "LABEL " + "\n      ".join(lines).rstrip(" \\\n") + "\n"


def readme_table(data: dict) -> str:
    sources = data["sources"]
    build = data["build"]
    rows = [
        ("Base image", base_reference(data)),
        ("llama-cpp-python", f"{sources['llama_cpp_python']['version']} (source build)"),
        ("llama.cpp", f"{sources['llama_cpp']['version']} (source build)"),
        ("Python", build["python_version"]),
        ("HIP targets", build["amd_gpu_targets"]),
        (
            "Default test model",
            f"{data['test']['model_file']} "
            f"({data['test']['model_repository'].split('/')[-1]})",
        ),
    ]
    body = "".join(f"| {name} | {version} |\n" for name, version in rows)
    return "| Component | Version |\n| --- | --- |\n" + body.rstrip("\n") + "\n"


def replace_between(text: str, begin: str, end: str, body: str) -> str:
    """Swap the content between two marker lines, keeping the markers."""
    head, marker, rest = text.partition(begin)
    if not marker:
        raise SystemExit(f"marker not found: {begin.strip()!r}")
    _, marker, tail = rest.partition(end)
    if not marker:
        raise SystemExit(f"marker not found: {end.strip()!r}")
    return head + begin + body + end + tail


def render(data: dict) -> dict[str, str]:
    """Every generated file, fully rendered: path -> expected content."""
    dockerfile = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    dockerfile = replace_between(dockerfile, ARGS_BEGIN, ARGS_END, args_block(data))
    dockerfile = replace_between(dockerfile, LABELS_BEGIN, LABELS_END, labels_block(data))
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    readme = replace_between(readme, README_BEGIN, README_END, readme_table(data))
    return {
        "requirements-build.in": build_requirements_in(data),
        "requirements-runtime.in": runtime_requirements_in(data),
        "Dockerfile": dockerfile,
        "README.md": readme,
    }


def sync() -> int:
    data = load()
    changed = []
    for name, content in render(data).items():
        path = ROOT / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            changed.append(name)
    print("updated: " + ", ".join(changed) if changed else "everything already current")
    return 0


def check() -> int:
    stale = [
        name
        for name, content in render(load()).items()
        if (ROOT / name).read_text(encoding="utf-8") != content
    ]
    if stale:
        print("out of date, run `make versions`: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("versions.json is in sync")
    return 0


def main(argv: list[str]) -> int:
    command = argv[1] if len(argv) > 1 else "check"
    data = load()
    printers = {
        "args": args_block,
        "labels": labels_block,
        "readme": readme_table,
    }
    if command in printers:
        print(printers[command](data), end="")
        return 0
    if command == "sync":
        return sync()
    if command == "check":
        return check()
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
